// 2. Hardened Reference Template: ShopFast (Resilient)
// ========================================================
export const shopFastHardenedTemplate: ArchitectureSpec = {
  ...shopFastNaiveTemplate,
  name: 'ShopFast (Hardened Reference)',
  description: 'Hardened architecture with circuit breakers, exponential backoff with jitter, load shedding, and orders-db redundancy.',
  services: shopFastNaiveTemplate.services.map((svc) => {
    if (svc.id === 'gateway') {
      return {
        ...svc,
        instances: { initial: 6, min: 4, max: 14 },
        load_shedding: { enabled: true, threshold: 0.8 },
      };
    }
    if (svc.id === 'checkout') {
      return {
        ...svc,
        instances: { initial: 5, min: 4, max: 12 },
      };
    }
    if (svc.id === 'orders-db') {
      return {
        ...svc,
        instances: { initial: 2, min: 2, max: 4 }, // Fixed SPOF
        zone_spread: ['a', 'b'],
      };
    }
    return svc;
  }),
  edges: shopFastNaiveTemplate.edges.map((edge) => {
    const baseBackoff =
      edge.retries > 0
        ? {
            mode: 'exponential' as const,
            jitter: true,
            base_delay_ms: edge.backoff?.base_delay_ms || 50,
            max_delay_ms: edge.backoff?.max_delay_ms || 1000,
          }
        : edge.backoff;

    if (edge.from === 'gateway' && edge.to === 'checkout') {
      return {
        ...edge,
        retries: 0,
        backoff: { mode: 'exponential' as const, jitter: true, base_delay_ms: 100, max_delay_ms: 1000 },
        circuit_breaker: { enabled: true, failure_rate_threshold: 0.5, min_calls: 10, open_duration_s: 15, probe_fraction: 0.1 },
      };
    }
    if (edge.from === 'checkout' && edge.to === 'payments') {
      return {
        ...edge,
        retries: 1,
        backoff: { mode: 'exponential' as const, jitter: true, base_delay_ms: 100, max_delay_ms: 1500 },
        circuit_breaker: { enabled: true, failure_rate_threshold: 0.5, min_calls: 10, open_duration_s: 15, probe_fraction: 0.1 },
      };
    }
    if (edge.from === 'payments' && edge.to === 'payment-provider') {
      return {
        ...edge,
        retries: 1,
        backoff: { mode: 'exponential' as const, jitter: true, base_delay_ms: 150, max_delay_ms: 2000 },
        circuit_breaker: { enabled: true, failure_rate_threshold: 0.4, min_calls: 10, open_duration_s: 20, probe_fraction: 0.05 },
      };
    }
    return {
      ...edge,
      backoff: baseBackoff,
      circuit_breaker:
        edge.critical && edge.mode === 'sync'
          ? {
              enabled: true,
              failure_rate_threshold: 0.5,
              min_calls: 10,
              open_duration_s: 15,
              probe_fraction: 0.1,
            }
          : edge.circuit_breaker,
    };
  }),
};

